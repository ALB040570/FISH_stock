import { describe, expect, it } from 'vitest'
import { CABINETS, cabinetOf, cabinetsFor, canGo, helpRoute, homeFor, legacyToNew, mainPage } from './cabinets'

describe('кабинеты', () => {
  it('адрес → кабинет', () => {
    expect(cabinetOf('/monitoring/waterbody/zhaysan?sp=x').key).toBe('monitoring')
    expect(cabinetOf('/input/datasets/01AB').key).toBe('input')
    expect(cabinetOf('/admin').key).toBe('admin')
    expect(cabinetOf('/login')).toBeNull()
    expect(cabinetOf('/')).toBeNull()
  })
  it('доступ ролей', () => {
    expect(cabinetsFor('viewer').map((c) => c.key)).toEqual(['monitoring'])
    expect(cabinetsFor('operator').map((c) => c.key)).toEqual(['monitoring', 'input'])
    expect(canGo('/calc/runs/1', 'operator')).toBe(false)
    expect(canGo('/input/datasets/1', 'operator')).toBe(true)
    expect(cabinetsFor('ichthyologist').map((c) => c.key)).toEqual(['monitoring', 'input', 'calc', 'design'])
    expect(cabinetsFor('mathematician').length).toBe(5)
    expect(cabinetsFor('admin').length).toBe(5)
    expect(canGo('/calc/runs/1', 'viewer')).toBe(false)
    expect(canGo('/monitoring/help/x', 'viewer')).toBe(true)
    expect(CABINETS.every((c) => c.base.startsWith('/') && c.base.endsWith('/'))).toBe(true)
  })
  it('«Презентация»: просмотр без администрирования, с «Потоком» (№ 62)', () => {
    expect(cabinetsFor('presenter').map((c) => c.key)).toEqual(['monitoring', 'input', 'calc', 'design'])
    expect(canGo('/admin/users', 'presenter')).toBe(false)
    expect(mainPage('presenter')).toBe('/')
    expect(homeFor('presenter', '/admin/catalog')).toBe('/')
  })
  it('старые адреса', () => {
    expect(legacyToNew('/data?wb=zhaysan')).toBe('/input/datasets?wb=zhaysan')
    expect(legacyToNew('/data/01AB')).toBe('/input/datasets/01AB')
    expect(legacyToNew('/runs/01AB')).toBe('/calc/runs/01AB')
    expect(legacyToNew('/calculations?wb=z')).toBe('/calc/calculations?wb=z')
    expect(legacyToNew('/profiles')).toBe('/calc/profiles')
    expect(legacyToNew('/dictionaries/types/catches')).toBe('/design/dictionaries/types/catches')
    expect(legacyToNew('/algorithms/drafts/1')).toBe('/design/algorithms/drafts/1')
    expect(legacyToNew('/dashboards/abc')).toBe('/monitoring/dashboards/abc')
    expect(legacyToNew('/catalog')).toBe('/admin/catalog')
    expect(legacyToNew('/users')).toBe('/admin/users')
    expect(legacyToNew('/help/map')).toBe('/monitoring/help/map')
    expect(legacyToNew('/monitoring/zhaysan?sp=bream&tab=pdu')).toBe('/monitoring/waterbody/zhaysan?sp=bream&tab=pdu')
    expect(legacyToNew('/monitoring')).toBeNull()
    expect(legacyToNew('/monitoring/waterbody/zhaysan')).toBeNull()
    expect(legacyToNew('/design/calculations/1')).toBeNull()
    expect(legacyToNew('/datasets')).toBeNull()
    expect(legacyToNew('/')).toBeNull()
  })
  it('адрес для справки — в старом виде', () => {
    expect(helpRoute('/monitoring/')).toBe('/')
    expect(helpRoute('/monitoring/waterbody/zhaysan')).toBe('/monitoring/zhaysan')
    expect(helpRoute('/input/datasets/01AB')).toBe('/data/01AB')
    expect(helpRoute('/input/')).toBe('/data')
    expect(helpRoute('/calc/runs/01AB')).toBe('/runs/01AB')
    expect(helpRoute('/design/dictionaries')).toBe('/dictionaries')
    expect(helpRoute('/design/calculations/5')).toBe('/design/calculations/5')
    expect(helpRoute('/admin/audit')).toBe('/audit')
    expect(helpRoute('/calc/help/runs')).toBe('/help/runs')
  })
  it('куда после входа', () => {
    expect(homeFor('viewer')).toBe('/monitoring/')
    expect(homeFor('admin')).toBe('/')
    expect(homeFor('admin', '/runs/1')).toBe('/calc/runs/1')
    expect(homeFor('viewer', '/admin/users')).toBe('/monitoring/')
    expect(homeFor('viewer', '//evil.example')).toBe('/monitoring/')
    expect(homeFor('ichthyologist', '/monitoring/waterbody/z')).toBe('/monitoring/waterbody/z')
    expect(homeFor('ichthyologist')).toBe('/')
    expect(homeFor('mathematician')).toBe('/')
    expect(homeFor('operator')).toBe('/input/')
    expect(homeFor('operator', '/monitoring/waterbody/z')).toBe('/monitoring/waterbody/z')
    expect(mainPage('viewer')).toBe('/monitoring/')
  })
})
