def test_table_6_net_parabola_edges():
    """Таблица 6 (2015): у параболы сети края c̄/3 и 2c̄/3, среднее равно c̄; лещ — c̄ = 0,2, вершина 5, m1 = 16."""
    ages = np.arange(2, 17)
    obs = np.where(ages == 5, 10.0, 1.0)
    p = fit_parabola(ages, obs, m0=4, c_mean=0.2)
    c = p.at(ages) if hasattr(p, "at") else np.where(ages <= p.peak, p.c0 - p.a1 * (ages - p.peak) ** 2, p.c0 - p.a2 * (ages - p.peak) ** 2)
    assert p.peak == 5 and abs(c.mean() - 0.2) < 1e-12
    assert abs(c[0] - 0.2 / 3) < 1e-12 and abs(c[-1] - 0.4 / 3) < 1e-12
    # значения таблицы 6 для леща (округление до 0,01)
    assert [round(v, 2) for v in c] == [0.07, 0.17, 0.23, 0.25, 0.25, 0.25, 0.24, 0.24, 0.23, 0.22, 0.2, 0.19, 0.17, 0.15, 0.13]
