"""
Подписи возрастов.

Возраст j в данных (LessAge = less_j) — рыбы в возрасте от j−1 до j лет.
Подписываем его как «1–2», «2–3» и т. д. (решение автора от 29.09.2026).
"""


def age_label(j) -> str:
    """less_j → «(j−1)–j», например 2 → «1–2»."""
    j = int(j)
    return f"{j - 1}–{j}"


def age_title(j) -> str:
    """less_j → «1–2 года», «4–5 лет»."""
    j = int(j)
    unit = "года" if j % 10 in (2, 3, 4) and j % 100 not in (12, 13, 14) else "лет"
    return f"{j - 1}–{j} {unit}"
