"""
Настройки проекта fish_stock_forecast.

Исходные данные (уловы, возрастные пробы, свойства видов) читаются из
существующего проекта fish_stock_assesment_1 и НЕ копируются.
Путь к нему можно переопределить переменной окружения FISH_SOURCE_DIR.
"""
import os
from pathlib import Path

# Корень нового проекта: .../fish_stock_forecast
PROJECT_ROOT = Path(__file__).resolve().parent.parent

# Исходный проект: по умолчанию лежит рядом, в той же папке pythonprojects
SOURCE_PROJECT_DIR = Path(
    os.environ.get("FISH_SOURCE_DIR", PROJECT_ROOT.parent / "fish_stock_assesment_1")
)
DATA_CATCH_DIR = SOURCE_PROJECT_DIR / "data_catch"      # исходные уловы и свойства видов
OLD_DATA_STOCK_DIR = SOURCE_PROJECT_DIR / "data_stock"  # старые результаты (только чтение)

# Куда новый проект сохраняет свои результаты
RESULTS_DIR = PROJECT_ROOT / "results"

# Водоём по умолчанию
WATERBODY = os.environ.get("FISH_WATERBODY", "zhaysan")

# Названия орудий лова так, как они записаны в исходных данных
GEAR_SEINE = "невод"
GEAR_NET = "сеть"

# ---------------------------------------------------------------------------
# Уловистость невода (МНК-подгонка сигмоиды), формулы (24)-(26) статьи
# ---------------------------------------------------------------------------
SEINE_MIN_AGE = 2            # одногодки в уловах не встречаются: возрасты 2..m1
SEINE_C_LOWER = 0.1          # ограничение (26) снизу для групп 3 и старше
SEINE_C_LOWER_FIRST = 0.01   # нижняя граница для двухлеток (группа 2: возраст от 1 до 2 лет)
SEINE_C_UPPER = 0.8          # ограничение (26) сверху
SEINE_MIN_SAMPLE = 20        # если в пробе меньше рыб — берём пробу вида за все годы

# ---------------------------------------------------------------------------
# Уловистость сети — парабола, формулы (22)-(24) статьи
# ---------------------------------------------------------------------------
NET_MIN_AGE = 2              # первая возрастная группа в уловах (двухлетки); в статье — 1
# Края параболы — доли среднего c̄ (решение автора от 16.10.2026, ответ рецензентам):
#   c(j_min) = c̄/3,  c(m1) = 2c̄/3.  При c̄ = 0.3 это прежние 0.1 и 0.2.
NET_END_LEFT_FRAC = 1 / 3    # c̄ − a1·(j_min − c¹)² = c̄/3
NET_END_RIGHT_FRAC = 2 / 3   # c̄ − a2·(m1 − c¹)² = 2c̄/3
NET_C_LOWER_FRAC = 1 / 3     # ограничение (24) снизу: c ≥ c̄/3
NET_C_UPPER = 0.8            # ограничение (24) сверху
NET_MIN_SAMPLE = 20          # если в пробе меньше рыб — берём пробу вида за все годы

# ---------------------------------------------------------------------------
# Запас по уловам
# ---------------------------------------------------------------------------
HECTARE_M2 = 10_000          # обловленная площадь невода задана в гектарах
KM2_M2 = 1_000_000           # площадь водоёма задана в км²
NPC_STOCK_MULTIPLIER = 1000  # оценка запаса НПЦ умножается на 1000, как в calc_stock_npc.py

# Формула запаса по сетям:
#   "code"    — как в calc_stock_net старого проекта: X = Y·S / (σ·(V² − r0²)), r0 = длина сети / 2
#   "article" — формула (28) статьи:                   X = Y·S / (π·V²·σ)
NET_STOCK_FORMULA = "article"   # решение автора от 16.10.2026 (было "code" с 29.09.2026)

# Окончательный годовой запас по каждому возрасту — объединение оценок сети и невода:
#   "hauls" — средневзвешенное по числу ловов каждого орудия в году (решение автора от 29.09.2026)
#   "mean"  — простое среднее, формула (29) статьи
# Суммарный годовой запас — сумма окончательных запасов по всем возрастам.
COMBINE_GEARS = "hauls"

# Модель баланса сети: подшаги внутри круга 0 (решение автора от 16.10.2026).
# За час рыба проходит V метров, а радиус круга 0 — всего r0 = длина сети / 2, поэтому внутри
# круга 0 час делится на n подшагов; на каждом подшаге 1/4 рыб круга 0 встречает сеть, 1/4 выходит
# в кольцо 1, 1/2 остаётся, а приток из кольца 1 за час делится поровну между подшагами.
#   "auto" — n = ⌈V / r0⌉ (за подшаг рыба проходит не больше r0); число — фиксированное n; 1 — без подшагов.
NET_ZONE0_SUBSTEPS = "auto"

# Число сетей одного размера ячеи в лове (решение автора от 18.10.2026). Полотна разной ячеи ловят
# рыб разного возраста и вместе считаются одной сетью; если на каждую ячею ставится n полотен,
# они ловят в √n раз больше одного (вывод в статье: эквивалентный круг радиуса √n·V).
# Улов лова приводится к одной сети делением на √n, затем применяется (28):
#     X = Y · S / (√n · π V² σ).
# Научные ловы — по две сети на каждую ячею (n = 2); промысловые — n = 1 (число сетей неизвестно).
# "sqrt" — поправка √n; "one" — n = 1 для всех ловов (как до 18.10.2026).
NET_PANELS_MODE = "sqrt"
NET_PANELS_BY_CATCH_TYPE = {"научный": 2, "промысловый": 1}
NET_PANELS_DEFAULT = 1

# Сглаживание возрастной пробы (замечание рецензента 3, п. 21–22; решение автора от 18.10.2026).
# Было: +1 к каждой возрастной группе j <= m1 (до 12–15 «фантомных» рыб при пробе в 10–11 рыб).
# Стало: к группам j <= m1 добавляется AGE_PSEUDOCOUNT_TOTAL / J (J — число таких групп), т. е. всего
# одна условная рыба — априорное Дирихле с параметром концентрации 1/J. Если в пробе вида за год меньше
# AGE_POOL_MIN_SAMPLE рыб, к ней прибавляются пробы соседних лет (± AGE_POOL_NEIGHBOURS).
# Прежнее поведение: AGE_PSEUDOCOUNT_TOTAL = None (по 1 на группу), AGE_POOL_MIN_SAMPLE = 0.
AGE_PSEUDOCOUNT_TOTAL = 1.0
AGE_POOL_MIN_SAMPLE = 30
AGE_POOL_NEIGHBOURS = 1

# ---------------------------------------------------------------------------
# Распределение ПДУ НПЦ по возрастам (раздел 5 статьи)
# ---------------------------------------------------------------------------
PDU_CAP = 0.75               # за одну итерацию — не больше 75 % остатка запаса возраста
PDU_MAX_ITER = 10_000        # итерации до исчерпания квоты или свободного запаса
PDU_TOL_G = 1.0              # квота считается исчерпанной, если осталось < 1 г
PDU_FREE_STOCK_TOL_G = 1.0   # свободного запаса нет, если его взвешенная биомасса < 1 г
