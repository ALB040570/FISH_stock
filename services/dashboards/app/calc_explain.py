def _catch_now(res, lang, **_):
    rows = [r for r in res.get("rows") or [] if r.get("observed") is not None]
    if not rows:
        return []
    top = max(rows, key=lambda r: r["observed"])
    tot = sum(r["observed"] for r in rows)
    return [L(lang, f"Больше всего в улове — возраст {top['age']} ({nf(top['observed'] / tot * 100, 0)} %).",
              f"Ауланымда ең көбі — {top['age']} жас ({nf(top['observed'] / tot * 100, 0)} %).")]


def _curve_now(res, lang, **_):
    rows = [r for r in res.get("rows") or [] if r.get("c") is not None]
    if not rows:
        return []
    lo = min(rows, key=lambda r: r["c"])
    hi = max(rows, key=lambda r: r["c"])
    return [L(lang, f"Наименьшая уловистость — у возраста {lo['age']} ({nf(lo['c'], 3)}), наибольшая — у {hi['age']} ({nf(hi['c'], 3)}).",
              f"Ең аз аулағыштық — {lo['age']} жаста ({nf(lo['c'], 3)}), ең көбі — {hi['age']} жаста ({nf(hi['c'], 3)}).")]


