def _pc(v, lang="ru"):
    if v is None:
        return "—"
    a = abs(v)
    if a >= 1e6:
        return f"{nf(v / 1e6, 1)} млн"
    if a >= 1e3:
        return f"{nf(v / 1e3, 0)} {'мың' if lang == 'kk' else 'тыс'}"
    return nf(v, 0)


def _st_species_now(res, lang, **_):
    rows = [r for r in res.get("rows") or [] if r.get("mean")]
    if not rows:
        return []
    top = rows[0]
    out = [L(lang, f"{res.get('year')} г.: наибольший окончательный запас — {top['species']} ({_pc(top['mean'], lang)} шт).",
             f"{res.get('year')} ж.: ең үлкен түпкілікті қор — {top['species']} ({_pc(top['mean'], lang)} дана).")]
    big = [r["species"] for r in rows if r.get("ratio") and r["ratio"] >= 3]
    if big:
        out.append(L(lang, "Невод даёт в 3 раза и больше, чем сети: " + ", ".join(big) + ".",
                     "Сүзекі аулардан 3 есе және одан көп береді: " + ", ".join(big) + "."))
    return out


def _st_tiles_now(res, lang, sp_name=None, **_):
    v = res.get("values") or {}
    out = [L(lang, f"{sp_name or ''}, {res.get('year')} г.: окончательный запас — {_pc(v.get('mean'), lang)} шт.",
             f"{sp_name or ''}, {res.get('year')} ж.: түпкілікті қор — {_pc(v.get('mean'), lang)} дана.")]
    if v.get("npc") and v.get("mean"):
        r = v["mean"] / v["npc"]
        if r >= 1:
            out.append(L(lang, f"Это в {nf(r, 1)} раза больше оценки НПЦ ({_pc(v['npc'], lang)} шт).",
                         f"Бұл ҒӨО бағасынан ({_pc(v['npc'], lang)} дана) {nf(r, 1)} есе көп."))
        else:
            out.append(L(lang, f"Это {nf(r * 100, 0)} % оценки НПЦ ({_pc(v['npc'], lang)} шт).",
                         f"Бұл ҒӨО бағасының ({_pc(v['npc'], lang)} дана) {nf(r * 100, 0)} %-ы."))
    return out


