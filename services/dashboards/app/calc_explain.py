def _species_now(res, lang, **_):
    rows = res.get("rows") or []
    flagged = [r["species"] for r in rows if r.get("status") and r["status"] != "ок"]
    out = [L(lang, f"{res.get('year')} г.: подогнано видов — {len(rows)}.", f"{res.get('year')} ж.: сәйкестендірілген түрлер — {len(rows)}.")]
    if flagged:
        out.append(L(lang, "С примечаниями (ограничение сработало или мало данных): " + ", ".join(flagged) + ".",
                     "Ескертпелері бар (шектеу іске қосылды немесе деректер аз): " + ", ".join(flagged) + "."))
    else:
        out.append(L(lang, "Ни у одного вида ограничения не сработали.", "Бірде-бір түрде шектеулер іске қосылмады."))
    return out


def _tiles_now(res, lang, sp_name=None, **_):
    f = res.get("fit") or {}
    c = f.get("c") or []
    sp = sp_name or ""
    if "j50" in f:
        out = [L(lang, f"{sp}, {res.get('year')} г.: уловистость растёт от {nf(c[0])} до {nf(c[-1])}; половины максимума достигает в возрасте j50 = {nf(f.get('j50'), 1)}.",
                 f"{sp}, {res.get('year')} ж.: аулағыштық {nf(c[0])}-ден {nf(c[-1])}-ге дейін өседі; максимумның жартысына j50 = {nf(f.get('j50'), 1)} жасында жетеді.")]
        out.append(L(lang, f"Подгонка: R² = {nf(f.get('r2'))}, проба {nf(f.get('n_sample'), 0)} рыб.",
                     f"Сәйкестендіру: R² = {nf(f.get('r2'))}, сынама {nf(f.get('n_sample'), 0)} балық."))
    else:
        out = [L(lang, f"{sp}, {res.get('year')} г.: вершина параболы — возраст {_age(f.get('peak'))}, c⁰ = {nf(f.get('c0'), 3)}.",
                 f"{sp}, {res.get('year')} ж.: парабола төбесі — {_age(f.get('peak'))} жас, c⁰ = {nf(f.get('c0'), 3)}.")]
        out.append(L(lang, f"Проба {nf(f.get('n_sample'), 0)} рыб, уловов {f.get('n_hauls')}.", f"Сынама {nf(f.get('n_sample'), 0)} балық, аулаулар {f.get('n_hauls')}."))
    if res.get("warnings"):
        out.append(L(lang, "Есть предупреждение — см. жёлтую строку.", "Ескерту бар — сары жолды қараңыз."))
    return out


def _catch_now(res, lang, **_):
    rows = [r for r in res.get("rows") or [] if r.get("observed") is not None]
    if not rows:
        return []
    top = max(rows, key=lambda r: r["observed"])
    tot = sum(r["observed"] for r in rows)
    return [L(lang, f"Больше всего в улове — возраст {top['age']} ({nf(top['observed'] / tot * 100, 0)} %).",
              f"Ауланымда ең көбі — {top['age']} жас ({nf(top['observed'] / tot * 100, 0)} %).")]


def _curve_now(res, lang, **_):
    rows = [r for r in res.get("rows") or [] if r.get("c") is not None]
    if not rows:
        return []
    lo = min(rows, key=lambda r: r["c"])
    hi = max(rows, key=lambda r: r["c"])
    return [L(lang, f"Наименьшая уловистость — у возраста {lo['age']} ({nf(lo['c'], 3)}), наибольшая — у {hi['age']} ({nf(hi['c'], 3)}).",
              f"Ең аз аулағыштық — {lo['age']} жаста ({nf(lo['c'], 3)}), ең көбі — {hi['age']} жаста ({nf(hi['c'], 3)}).")]


def _heat_now(res, lang, **_):
    rows = res.get("rows") or []
    if not rows:
        return []
    return [L(lang, f"Кривые за {len(rows)} лет ({rows[0]['year']}–{rows[-1]['year']}); выбран {res.get('year')} г.",
              f"{len(rows)} жылғы қисықтар ({rows[0]['year']}–{rows[-1]['year']}); {res.get('year')} ж. таңдалған.")]


def _params_now(res, lang, **_):
    rows = res.get("rows") or []
    bad = [str(r["year"]) for r in rows if r.get("status") and r["status"] != "ок"]
    if not bad:
        return [L(lang, "Во все годы ограничения не сработали.", "Барлық жылдарда шектеулер іске қосылмады.")]
    return [L(lang, "Годы с примечаниями: " + ", ".join(bad) + ".", "Ескертпелері бар жылдар: " + ", ".join(bad) + ".")]


