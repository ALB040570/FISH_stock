def _species_now(res, lang, **_):
    rows = res.get("rows") or []
    flagged = [r["species"] for r in rows if r.get("status") and r["status"] != "ок"]
    out = [L(lang, f"{res.get('year')} г.: подогнано видов — {len(rows)}.", f"{res.get('year')} ж.: сәйкестендірілген түрлер — {len(rows)}.")]
    if flagged:
        out.append(L(lang, "С примечаниями (ограничение сработало или мало данных): " + ", ".join(flagged) + ".",
                     "Ескертпелері бар (шектеу іске қосылды немесе деректер аз): " + ", ".join(flagged) + "."))
    else:
        out.append(L(lang, "Ни у одного вида ограничения не сработали.", "Бірде-бір түрде шектеулер іске қосылмады."))
    return out


