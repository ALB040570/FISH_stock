def L(lang, ru, kk):
    return kk if lang == "kk" else ru


def nf(v, d=2):
    if v is None:
        return "—"
    return f"{v:,.{d}f}".replace(",", " ").replace(".", ",")


def _age(j):
    try:
        j = float(j)
    except (TypeError, ValueError):
        return "—"
    return f"{int(round(j)) - 1}–{int(round(j))}" if abs(j - round(j)) < 1e-9 else nf(j, 1)


