def _pc(v, lang="ru"):
    if v is None:
        return "—"
    a = abs(v)
    if a >= 1e6:
        return f"{nf(v / 1e6, 1)} млн"
    if a >= 1e3:
        return f"{nf(v / 1e3, 0)} {'мың' if lang == 'kk' else 'тыс'}"
    return nf(v, 0)


