def tr(s):
    if not isinstance(s, str):
        return s
    for rx, rep in P:
        if rx.match(s):
            return rx.sub(rep, s)
    return s


def translate(res: dict) -> dict:
    """Перевести пояснения, сообщения и замечания результата представления на казахский."""
    if not isinstance(res, dict):
        return res
    for k in ("message", "formula", "title"):
        if k in res:
            res[k] = tr(res[k])
    if res.get("notes"):
        res["notes"] = [tr(n) for n in res["notes"]]
    for s in res.get("signals") or []:
        s["text"] = tr(s["text"])
    for r in res.get("rows") or []:
        for k in ("issue", "text"):
            if k in r:
                r[k] = tr(r[k])
    for i in res.get("issues") or []:
        i["issue"] = tr(i["issue"])
    return res
